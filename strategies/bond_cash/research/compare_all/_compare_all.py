def _load(rel):
    p = os.path.join(_BC, rel)
    if not os.path.exists(p):
        return []
    return [json.loads(x) for x in io.open(p, encoding="utf-8") if x.strip()]


def _pick_base(rows):
    """同窗口基准行（name 含「基准 v0 固定中性」）。"""
    return [r for r in rows if "基准 v0 固定中性" in (r.get("name") or "")]


def collect():
    """-> [(变种, 窗口标签, 年数, 变种指标, 基准指标)]，按 (jsonl 的 window 字段) 分组配对。"""
    out = []
    for key, rel, prefix, _desc in SPECS:
        rows = _load(rel)
        if not rows:
            continue
        # v1 的 jsonl 用 window 字段区分长窗/现行窗；其余文件只有一个窗口
        groups = {}
        for r in rows:
            w = (r.get("window") or "").strip() or "all"
            groups.setdefault(w, []).append(r)
        for w, sub in groups.items():
            base = _pick_base(sub)
            main = [r for r in sub if (r.get("name") or "").startswith(prefix)]
            if not base or not main:
                continue
            b, m = base[0], main[0]
            label = ("长窗" if "长窗" in w else "现行窗") if w != "all" else "单窗口"
            out.append((key, label, float(m.get("years") or 0), m, b))
    return out


