"""债腿家族横向对比：v0~v8 在同一窗口内「配对」比较，而不是横比绝对夏普。

为什么必须配对
--------------
各变种的回测窗口不同（v1 长窗 10.1 年、v2 4.7 年、v3/v4/v6 3.5 年、v5/v7/v8 4.9 年），
而**同一套债腿在不同窗口的夏普水平差很多**（3.5 年窗的 v0 基准 1.70、4.9 年窗 1.87），
直接比「谁是 1.83、谁是 1.52」会得出「v8 强于 v7 强于 v6」这种伪排序，其实只是窗口不同。

正确做法：每个变种的 `_vN_bt.md` 里都有一行**同窗口的 v0 固定中性 35/65 基准**，
把变种与它同窗口配对，算 Δ夏普 / Δ年化 / Δ回撤 / Δ最差年。跨窗口不可比的部分被抵消，
剩下的是「这个变种相对基准做了什么」。

产物
----
`_compare_all.md`：配对表（按 Δ夏普 排序）+ 窗口效应说明 + 可执行性清单。
只读各变种的 `backtest/_vN_bt.jsonl`，**不重跑任何策略**（口径由其自身回测保证）。

用法
----
    python strategies/bond_cash/research/compare_all/_compare_all.py
"""

