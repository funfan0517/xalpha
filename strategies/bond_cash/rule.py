# ---------------------------------------------------------------- 4. 纯映射
def bond_target(gate_on):
    """-> {code: 占**债腿**的比例}。gate_on=True 进攻档 / False 防守档。

    防守档与底仓是同一只（``core_off == base``）时必须**累加**而不是覆盖 ——
    否则防守档会算成 30%、凭空丢掉 70pp。
    """
    core = CFG["core_on"] if gate_on else CFG["core_off"]
    out = {}
    out[core] = out.get(core, 0.0) + CFG["core_w"]
    out[CFG["base"]] = out.get(CFG["base"], 0.0) + CFG["base_w"]
    return out


def cash_target():
    """-> {code: 占**现金腿**的比例}。"""
    return dict(CFG["cash"])


def to_pp(frac, sleeve_pp):
    """腿内比例 -> 总资产 pp。"""
    return {k: round(v * sleeve_pp, 2) for k, v in frac.items()}


