def temp_band(t):
    """温度 -> 档位名（<20 冰点 / <40 偏冷 / <60 中性 / <80 偏热 / ≥80 过热）。"""
    if t is None:
        return "—"
    name = "过热"
    for lo, nm in CFG["temp_bands"]:
        if t < lo:
            break
        name = nm
    return name


def discount(conf):
    return float(CFG["discount"].get(conf, CFG["discount"]["low"]))


def target_long(score, conf):
    """score/置信度 -> 长端目标占比（未加滞后带）。"""
    b, cap = CFG["long_base"], CFG["long_cap"]
    w = b + (score / 4.0) * (cap - b) * discount(conf)
    return float(min(max(w, CFG["long_floor"]), cap))


def confidence(score, conflict=False, degrade=False):
    """R-10 / R-11。"""
    conf = CFG["conf_by_abs"].get(abs(int(score)), "low")
    if conflict or degrade:
        return "low"
    return conf


def side(score, conflict=False):
    """R-09：互斥强制震荡观望。"""
    if conflict:
        return "震荡观望"
    if score >= CFG["side_up"]:
        return "偏多"
    if score <= CFG["side_down"]:
        return "偏空"
    return "震荡观望"


def in_freeze(today, dates=None):
    """R-19：距任一事件 ≤freeze_days 个自然日 -> True（只许减久期）。"""
    from datetime import date, datetime

    dates = POLICY_DATES if dates is None else dates
    if isinstance(today, str):
        today = datetime.strptime(today[:10], "%Y-%m-%d").date()
    if not isinstance(today, date):
        today = today.date()
    for d in dates:
        try:
            target = datetime.strptime(d[:10], "%Y-%m-%d").date()
        except ValueError:
            continue
        if abs((target - today).days) <= CFG["freeze_days"]:
            return True
    return False
