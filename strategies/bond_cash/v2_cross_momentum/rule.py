def is_rebalance(idx):
    """idx: DatetimeIndex -> bool Series（每月最后一个交易日 True）。

    **不能用「下一行是否换月」判断**：数据只到最新一天时，最后一行永远没有下一行，
    会被判成月末 → 每天用当日排名重置持仓（实测 v2 的「月度」轮动变成日频翻仓）。
    改为看**下一个工作日**是否跨月：与有没有未来数据无关，节假日只会让月底前移/后移一天。
    """
    import pandas as pd
    return pd.Series([(pd.Timestamp(d) + pd.offsets.BDay(1)).month != pd.Timestamp(d).month
                      for d in idx], index=idx)
