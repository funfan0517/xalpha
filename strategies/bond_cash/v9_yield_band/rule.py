def is_rebalance(idx, freq=None):
    """月末 / 周末最后交易日 -> bool Series。

    用「下一工作日是否跨月/跨周」判断，避免数据末行被误判成调仓日。
    """
    import pandas as pd

    freq = (CFG["rebalance"] if freq is None else freq)
    idx = pd.DatetimeIndex(idx)
    if freq == "week_end":
        return pd.Series([(d + pd.offsets.BDay(1)).isocalendar().week != d.isocalendar().week
                          for d in idx], index=idx)
    return pd.Series([(d + pd.offsets.BDay(1)).month != d.month for d in idx], index=idx)
