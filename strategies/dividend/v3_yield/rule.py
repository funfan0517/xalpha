"""V3 · 股息率单指标红利策略 —— 参数权威源（`RULES.md` 是文字版）

指标
----
`股息率(dy)`：指数股息率，来自 `data/_div_yield_m.csv`（`000922`/`H30269` 为全收益反推的
真实实现股息率，其余为变化率代理 + 官网快照校准）。**越高 = 越便宜**。

贵度
----
```
q = 1 − 分位(dy)      # 分位为扩张窗口（≥36 月、≤120 月），逐只基金用自身历史
```
`q` 越低越便宜，0 = 该基金自身历史最便宜。

决策
----
* 时间维度（板块层）：q̄ = 7 只均值；`q̄ ≥ 0.80` 清仓、`0.50 ≤ q̄ < 0.80` 减半、否则满仓。
* 横截面：每月选 q 最低的 `TOP_K` 只等权。
* 月末信号、下月生效、单边 0.03%。

口径提醒（写进报告，不隐藏）
----------------------------
股息率是**慢变量**：分位在 3–5 年尺度上变化很小，时间维度容易长期停在同一档；
横截面则受"股息率的分子（分红）与分母（价格）谁在动"影响 —— 价格暴跌会把股息率顶高，
此时"便宜"其实是"刚跌过"，这也是红利策略最容易吃亏的地方（股息陷阱/周期顶）。
"""

